/**
 * ParsedReceiptItem
 *
 * Represents one line item parsed from a scanned receipt.
 * Returned by POST /api/v1/receipts/scan inside the line_items array.
 *
 * The `selected` field is frontend-only — it drives the checkboxes on
 * ReceiptConfirmScreen so the user can deselect items they don't want added.
 * It is never sent to the backend.
 */
export interface ParsedReceiptItem {
  /** Product name extracted from the receipt, e.g. "Organic Whole Milk" */
  item: string;
  /** Price per unit as shown on the receipt, e.g. 3.99 */
  price: number;
  /** How many of this item were purchased, e.g. 2 */
  quantity: number;
  /** Auto-detected category e.g. "dairy", "produce" — may be "pantry" if unknown */
  category: string;
  /**
   * Whether this item is checked on the confirm screen.
   * Defaults to true (all items selected). User can uncheck items they
   * don't want added to their pantry.
   * NOT sent to the backend.
   */
  selected: boolean;
}

